import { copyFile, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { rollup } from "rollup";
import dts from "rollup-plugin-dts";
import { build as viteBuild } from "vite";

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoDir = resolve(packageDir, "../..");
const distDir = resolve(packageDir, "dist");

const packageManifest = JSON.parse(
  await readFile(resolve(packageDir, "package.json"), "utf8"),
);
const workspaceSources = new Map([
  ["@ten4seven/icons", resolve(repoDir, "packages/icons/src/index.tsx")],
  ["@ten4seven/tokens", resolve(repoDir, "packages/tokens/src/index.ts")],
]);

await rm(distDir, { force: true, recursive: true });

await viteBuild({
  configFile: resolve(packageDir, "vite.config.ts"),
  root: packageDir,
});

const declarationBundle = await rollup({
  input: resolve(packageDir, "src/index.ts"),
  plugins: [
    {
      name: "ten4seven-workspace-declaration-aliases",
      resolveId(source) {
        return workspaceSources.get(source) ?? null;
      },
    },
    dts({ respectExternal: false }),
  ],
});

try {
  await declarationBundle.write({
    file: resolve(distDir, "index.d.ts"),
    format: "es",
  });
} finally {
  await declarationBundle.close();
}

const [themeCss, componentCss] = await Promise.all([
  readFile(resolve(repoDir, "packages/tokens/src/theme.css"), "utf8"),
  readFile(resolve(packageDir, "src/styles.css"), "utf8"),
]);

await writeFile(
  resolve(distDir, "styles.css"),
  [
    "/* Generated by @ten4seven/ui. Tokens precede component contracts. */",
    themeCss.trim(),
    componentCss.trim(),
    "",
  ].join("\n\n"),
  "utf8",
);

const fontsDir = resolve(distDir, "fonts");
await mkdir(fontsDir, { recursive: true });
await Promise.all([
  copyFile(
    resolve(repoDir, "packages/tokens/src/fonts/Inter-Variable.woff2"),
    resolve(fontsDir, "Inter-Variable.woff2"),
  ),
  copyFile(
    resolve(repoDir, "packages/tokens/src/fonts/Inter-OFL.txt"),
    resolve(fontsDir, "Inter-OFL.txt"),
  ),
]);

await writeFile(
  resolve(distDir, "package-build.json"),
  `${JSON.stringify(
    {
      name: packageManifest.name,
      version: packageManifest.version,
      entry: "index.js",
      commonjsEntry: "index.cjs",
      declarations: "index.d.ts",
      stylesheet: "styles.css",
      includes: ["tokens", "semantic-icons", "react-components", "motion"],
    },
    null,
    2,
  )}\n`,
  "utf8",
);

console.log(
  `Built ${packageManifest.name}@${packageManifest.version} at ${distDir}`,
);
