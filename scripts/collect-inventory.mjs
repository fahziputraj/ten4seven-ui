function packageSummary(relativePath) {
  const file = path.join(relativePath, "package.json");
  const pkg = readJson(file);
  if (!pkg) return null;
  return {
    name: pkg.name ?? path.basename(relativePath),
    version: pkg.version ?? "",
    license: pkg.license ?? "not declared",
    dependencies: Object.keys(pkg.dependencies ?? {}),
    devDependencies: Object.keys(pkg.devDependencies ?? {}),
    path: file,
  };
}

